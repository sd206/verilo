/**
 * Inbound email (section 9) from Postmark's inbound webhook (JSON). Postmark doesn't sign inbound
 * posts, so the webhook URL carries HTTP basic-auth credentials (Postmark's documented approach);
 * the password is the POSTMARK_INBOUND_WEBHOOK_SECRET secret.
 */
import { timingSafeEqual, createHash } from "node:crypto";
import { z } from "zod";

export const MAX_INBOUND_BYTES = 25 * 1024 * 1024;
export const WEBHOOK_USER = "postmark";

/** Section 9: images, PDF, XLSX and CSV. XLSX/CSV are stored but not extracted in v1. */
export const INBOUND_ATTACHMENT_TYPES: Record<string, readonly string[]> = {
  "application/pdf": [".pdf"],
  "image/png": [".png"],
  "image/jpeg": [".jpg", ".jpeg"],
  "image/webp": [".webp"],
  "image/heic": [".heic"],
  "image/heif": [".heif"],
  "image/gif": [".gif"],
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet": [".xlsx"],
  "text/csv": [".csv"],
};

/** Signatures and logos are ignored (section 9). */
export const MIN_IMAGE_BYTES = 20 * 1024;
export const MIN_IMAGE_SHORT_SIDE = 200;

const address = z.object({ Email: z.string(), Name: z.string().optional().nullable() });

const postmarkSchema = z.object({
  From: z.string(),
  FromFull: address.optional(),
  FromName: z.string().optional().nullable(),
  To: z.string().optional().nullable(),
  ToFull: z.array(address).optional().default([]),
  CcFull: z.array(address).optional().default([]),
  BccFull: z.array(address).optional().default([]),
  OriginalRecipient: z.string().optional().nullable(),
  Subject: z.string().optional().nullable(),
  MessageID: z.string().min(1),
  Date: z.string().optional().nullable(),
  Headers: z.array(z.object({ Name: z.string(), Value: z.string() })).optional().default([]),
  Attachments: z
    .array(
      z.object({
        Name: z.string().optional().nullable(),
        Content: z.string(),
        ContentType: z.string(),
        ContentLength: z.number().optional(),
        ContentID: z.string().optional().nullable(),
      }),
    )
    .optional()
    .default([]),
});

export interface InboundAttachment {
  filename: string;
  contentType: string;
  content: Buffer;
  inline: boolean;
}

export interface InboundMessage {
  /** The original Message-ID header (falls back to the provider's id). */
  messageId: string;
  from: string;
  fromName: string | null;
  recipients: string[];
  subject: string | null;
  receivedAt: Date;
  headers: Record<string, string>;
  attachments: InboundAttachment[];
}

export class InboundParseError extends Error {}

export function parsePostmarkInbound(json: unknown, now: Date = new Date()): InboundMessage {
  const r = postmarkSchema.safeParse(json);
  if (!r.success) throw new InboundParseError(`Not a Postmark inbound payload: ${r.error.issues[0]?.message ?? "invalid"}`);
  const p = r.data;
  const headers: Record<string, string> = {};
  for (const h of p.Headers) headers[h.Name.toLowerCase()] = h.Value;
  const from = (p.FromFull?.Email ?? p.From).trim().toLowerCase();
  const recipients = [
    ...p.ToFull.map((a) => a.Email),
    ...p.CcFull.map((a) => a.Email),
    ...p.BccFull.map((a) => a.Email),
    ...(p.OriginalRecipient ? [p.OriginalRecipient] : []),
  ].map((a) => a.trim().toLowerCase());
  const date = p.Date ? new Date(p.Date) : now;
  return {
    messageId: (headers["message-id"] ?? p.MessageID).trim(),
    from,
    fromName: p.FromName ?? p.FromFull?.Name ?? null,
    recipients: [...new Set(recipients)],
    subject: p.Subject ?? null,
    receivedAt: Number.isNaN(date.getTime()) ? now : date,
    headers,
    attachments: p.Attachments.map((a, i) => ({
      filename: (a.Name ?? "").trim() || `attachment-${i + 1}`,
      contentType: a.ContentType.split(";")[0]!.trim().toLowerCase(),
      content: Buffer.from(a.Content, "base64"),
      inline: !!a.ContentID,
    })),
  };
}

/** RFC 3834 Auto-Submitted, Precedence: bulk/junk/list, and common auto-responder markers. */
export function isAutoGenerated(headers: Record<string, string>): boolean {
  const auto = headers["auto-submitted"]?.toLowerCase();
  if (auto && auto !== "no") return true;
  const prec = headers["precedence"]?.toLowerCase();
  if (prec && ["bulk", "junk", "list", "auto_reply"].includes(prec)) return true;
  return "x-autoreply" in headers || "x-autorespond" in headers;
}

export type AttachmentDecision = { keep: true } | { keep: false; reason: string };

/** Type rule only; the image size/dimension rule needs the decoded image (see the job). */
export function attachmentTypeAllowed(a: { filename: string; contentType: string }): boolean {
  const exts = INBOUND_ATTACHMENT_TYPES[a.contentType];
  if (!exts) return false;
  const lower = a.filename.toLowerCase();
  // Inline images often have no extension; accept those by type.
  return !lower.includes(".") || exts.some((e) => lower.endsWith(e));
}

/** Constant-time check of `Authorization: Basic …` against postmark:<secret>. */
export function verifyBasicAuth(header: string | null, secret: string | undefined): boolean {
  if (!secret || !header?.startsWith("Basic ")) return false;
  const expected = createHash("sha256").update(`${WEBHOOK_USER}:${secret}`).digest();
  let given: string;
  try {
    given = Buffer.from(header.slice(6).trim(), "base64").toString("utf8");
  } catch {
    return false;
  }
  return timingSafeEqual(expected, createHash("sha256").update(given).digest());
}
