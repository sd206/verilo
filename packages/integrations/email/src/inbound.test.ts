import { describe, expect, it } from "vitest";
import { attachmentTypeAllowed, isAutoGenerated, parsePostmarkInbound, verifyBasicAuth } from "./inbound";

const payload = {
  From: "Ravi Kumar <ravi@lonestar.test>",
  FromFull: { Email: "Ravi@Lonestar.test", Name: "Ravi Kumar" },
  ToFull: [{ Email: "ts-lonestar@inbound.test", Name: "" }],
  CcFull: [{ Email: "someone@x.test" }],
  Subject: "October timesheet",
  MessageID: "pm-123",
  Date: "Mon, 2 Nov 2026 09:00:00 -0600",
  Headers: [{ Name: "Message-ID", Value: "<abc@mail.test>" }],
  Attachments: [{ Name: "oct.png", Content: Buffer.from("png").toString("base64"), ContentType: "image/png", ContentID: "" }],
};

describe("parsePostmarkInbound", () => {
  it("normalizes addresses, uses the Message-ID header, and decodes attachments", () => {
    const m = parsePostmarkInbound(payload);
    expect(m.from).toBe("ravi@lonestar.test");
    expect(m.recipients).toEqual(["ts-lonestar@inbound.test", "someone@x.test"]);
    expect(m.messageId).toBe("<abc@mail.test>");
    expect(m.receivedAt.toISOString()).toBe("2026-11-02T15:00:00.000Z");
    expect(m.attachments[0]).toMatchObject({ filename: "oct.png", contentType: "image/png", inline: false });
    expect(m.attachments[0]!.content.toString()).toBe("png");
  });
  it("falls back to the provider id without a Message-ID header", () => {
    expect(parsePostmarkInbound({ ...payload, Headers: [] }).messageId).toBe("pm-123");
  });
  it("rejects payloads that aren't Postmark's", () => {
    expect(() => parsePostmarkInbound({ hello: 1 })).toThrow(/Postmark/);
  });
});

describe("loop protection (section 9)", () => {
  it("spots auto-generated mail", () => {
    expect(isAutoGenerated({ "auto-submitted": "auto-replied" })).toBe(true);
    expect(isAutoGenerated({ "auto-submitted": "no" })).toBe(false);
    expect(isAutoGenerated({ precedence: "bulk" })).toBe(true);
    expect(isAutoGenerated({ "x-autoreply": "yes" })).toBe(true);
    expect(isAutoGenerated({})).toBe(false);
  });
});

describe("attachment types", () => {
  it("allows images, PDF, XLSX and CSV only", () => {
    expect(attachmentTypeAllowed({ filename: "a.pdf", contentType: "application/pdf" })).toBe(true);
    expect(attachmentTypeAllowed({ filename: "a.csv", contentType: "text/csv" })).toBe(true);
    expect(attachmentTypeAllowed({ filename: "a.exe", contentType: "application/octet-stream" })).toBe(false);
    expect(attachmentTypeAllowed({ filename: "a.docx", contentType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document" })).toBe(false);
    expect(attachmentTypeAllowed({ filename: "a.pdf.exe", contentType: "application/pdf" })).toBe(false);
    expect(attachmentTypeAllowed({ filename: "image001", contentType: "image/png" })).toBe(true);
  });
});

describe("verifyBasicAuth", () => {
  const h = (s: string) => `Basic ${Buffer.from(s).toString("base64")}`;
  it("accepts postmark:<secret> only", () => {
    expect(verifyBasicAuth(h("postmark:s3cret"), "s3cret")).toBe(true);
    expect(verifyBasicAuth(h("postmark:wrong"), "s3cret")).toBe(false);
    expect(verifyBasicAuth(h("other:s3cret"), "s3cret")).toBe(false);
    expect(verifyBasicAuth(null, "s3cret")).toBe(false);
    expect(verifyBasicAuth(h("postmark:"), undefined)).toBe(false);
  });
});
