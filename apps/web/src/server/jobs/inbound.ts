/**
 * Inbound timesheet email (section 9): POST /api/inbound-email/:provider stores the raw message
 * and queues process_inbound_email, which turns attachments into scanned files and evidence, then
 * extraction (8.1) and matching (8.6) take over. Nothing is ever submitted automatically.
 */
import { randomUUID } from "node:crypto";
import { Readable } from "node:stream";
import {
  countEvidenceForEmail,
  getFirm,
  getInboundEmail,
  inboxLookup,
  insertFile,
  insertInboundEmail,
  listConsultants,
  recordScanResult,
  updateInboundEmail,
  withAnonymous,
  withFirm,
  type FileRow,
} from "@verilo/db";
import { inboundEmailMachine, matchConsultant } from "@verilo/domain";
import {
  attachmentTypeAllowed,
  autoReplyEmail,
  InboundParseError,
  isAutoGenerated,
  MAX_INBOUND_BYTES,
  MIN_IMAGE_BYTES,
  MIN_IMAGE_SHORT_SIDE,
  parsePostmarkInbound,
  verifyBasicAuth,
  type InboundMessage,
} from "@verilo/email";
import { imageSize } from "@verilo/ai";
import { storageKeyFor } from "@verilo/storage";
import type { JobPayloads } from "@verilo/jobs";
import type { Deps } from "../deps";
import { attachEvidence, audit, recordUsage, settleInboundEmail, type Actor, type PendingJob } from "../timesheets/service";

/** Base64 inflates by 4/3; leave room for the JSON around the attachments. */
const MAX_BODY_BYTES = Math.ceil(MAX_INBOUND_BYTES * 1.4) + 1024 * 1024;

const rawKey = (firmId: string, id: string) => `firms/${firmId}/inbound/${id}.json`;

/** POST /api/inbound-email/:provider */
export async function receiveInboundEmail(d: Deps, req: Request, provider: string): Promise<Response> {
  if (provider !== "postmark") return Response.json({ error: "Unknown provider" }, { status: 404 });
  if (!verifyBasicAuth(req.headers.get("authorization"), d.config.inboundWebhookSecret)) {
    return Response.json({ error: "Unauthorized" }, { status: 401, headers: { "www-authenticate": 'Basic realm="inbound"' } });
  }
  const declared = Number(req.headers.get("content-length") ?? "0");
  if (declared > MAX_BODY_BYTES) return Response.json({ error: "Email is larger than 25 MB" }, { status: 413 });
  const body = Buffer.from(await req.arrayBuffer());
  if (body.length > MAX_BODY_BYTES) return Response.json({ error: "Email is larger than 25 MB" }, { status: 413 });

  let msg: InboundMessage;
  try {
    msg = parsePostmarkInbound(JSON.parse(body.toString("utf8")));
  } catch (e) {
    if (e instanceof InboundParseError || e instanceof SyntaxError) return Response.json({ error: "Invalid payload" }, { status: 400 });
    throw e;
  }

  const targets = await withAnonymous(d.db, (tx) => inboxLookup(tx, msg.recipients));
  const stored: string[] = [];
  for (const t of targets) {
    const id = randomUUID();
    const key = rawKey(t.firmId, id);
    await d.storage.put(key, body, "application/json");
    const row = await withFirm(d.db, t.firmId, async (tx) => {
      const r = await insertInboundEmail(tx, t.firmId, {
        inbox: t.inbox,
        messageId: msg.messageId,
        fromAddress: msg.from,
        subject: msg.subject,
        receivedAt: msg.receivedAt,
        rawStorageKey: key,
      });
      if (r) await audit(tx, { firmId: t.firmId, userId: null, role: null }, "inbound_email", r.id, "create", null, { inbox: r.inbox, messageId: r.messageId, from: r.fromAddress });
      return r;
    });
    if (!row) continue; // duplicate Message-ID (section 9)
    stored.push(row.id);
    await d.jobs.send("process_inbound_email", { firmId: t.firmId, inboundEmailId: row.id }, { singletonKey: row.id });
  }
  if (targets.length === 0) d.log.info({ recipients: msg.recipients.length }, "inbound email for no known inbox");
  // 200 even when nothing matched, so the provider doesn't retry.
  return Response.json({ ok: true, stored: stored.length });
}

async function readAll(stream: Readable): Promise<Buffer> {
  const chunks: Buffer[] = [];
  for await (const c of stream) chunks.push(Buffer.from(c as Buffer));
  return Buffer.concat(chunks);
}

interface Prepared {
  fileId: string;
  filename: string;
  contentType: string;
  sizeBytes: number;
  scan: Awaited<ReturnType<Deps["scanner"]["scan"]>>;
}

export async function processInboundEmailJob(d: Deps, { firmId, inboundEmailId }: JobPayloads["process_inbound_email"]): Promise<void> {
  const system: Actor = { firmId, userId: null, role: null };
  const email = await withFirm(d.db, firmId, (tx) => getInboundEmail(tx, firmId, inboundEmailId));
  if (!email || email.status !== "RECEIVED") return;
  // A retry after a crash: the attachments were already turned into evidence.
  if ((await withFirm(d.db, firmId, (tx) => countEvidenceForEmail(tx, firmId, email.id))).total > 0) {
    await withFirm(d.db, firmId, (tx) => settleInboundEmail(tx, system, email.id, null));
    return;
  }

  if (email.inbox === "AP") {
    await withFirm(d.db, firmId, (tx) =>
      updateInboundEmail(tx, firmId, email.id, "RECEIVED", { statusReason: "Vendor invoice intake starts with vendor bills (M4)" }),
    );
    return;
  }

  const msg = parsePostmarkInbound(JSON.parse((await readAll(await d.storage.getStream(email.rawStorageKey))).toString("utf8")));
  const reject = async (reason: string) =>
    withFirm(d.db, firmId, async (tx) => {
      const to = inboundEmailMachine.transition("RECEIVED", "REJECTED");
      await updateInboundEmail(tx, firmId, email.id, "RECEIVED", { status: to, statusReason: reason });
      await audit(tx, system, "inbound_email", email.id, "status_change", { status: "RECEIVED" }, { status: to }, reason);
    });

  const totalBytes = msg.attachments.reduce((s, a) => s + a.content.length, 0);
  if (totalBytes > MAX_INBOUND_BYTES) return reject("Email is larger than 25 MB");

  // Phase 1 (no transaction): filter, store and virus-scan each attachment.
  const skipped: string[] = [];
  const prepared: Prepared[] = [];
  for (const a of msg.attachments) {
    if (!attachmentTypeAllowed(a)) {
      skipped.push(`${a.filename} (type not accepted)`);
      continue;
    }
    if (a.contentType.startsWith("image/") && a.contentType !== "image/heic" && a.contentType !== "image/heif") {
      const size = await imageSize(a.content);
      // Signatures and logos (section 9).
      if (a.content.length < MIN_IMAGE_BYTES || (size && Math.min(size.width, size.height) < MIN_IMAGE_SHORT_SIDE)) continue;
    }
    const fileId = randomUUID();
    await d.storage.put(storageKeyFor(firmId, fileId), a.content, a.contentType);
    prepared.push({ fileId, filename: a.filename, contentType: a.contentType, sizeBytes: a.content.length, scan: await d.scanner.scan(Readable.from([a.content])) });
  }
  if (prepared.length === 0) {
    return reject(skipped.length ? `No usable attachments: ${skipped.join(", ")}` : "No timesheet attachment (image or PDF) found");
  }

  // Phase 2 (one transaction): files, scan results, sender match, evidence, extraction jobs.
  const { jobs, autoReply } = await withFirm(d.db, firmId, async (tx) => {
    const firm = (await getFirm(tx, firmId))!;
    const consultants = await listConsultants(tx, firmId);
    const m = matchConsultant(
      { fromAddress: msg.from, extractedName: null },
      consultants.filter((c) => !c.archivedAt).map((c) => ({ id: c.id, name: `${c.firstName} ${c.lastName}`, emails: c.emails, active: c.status === "ACTIVE" })),
    );
    const consultantId = m.matched ? m.consultantId : null;
    if (consultantId) await updateInboundEmail(tx, firmId, email.id, "RECEIVED", { matchedConsultantId: consultantId });

    const out: PendingJob[] = [];
    for (const p of prepared) {
      await insertFile(tx, {
        id: p.fileId,
        firmId,
        storageKey: storageKeyFor(firmId, p.fileId),
        filename: p.filename,
        mimeType: p.contentType,
        sizeBytes: p.sizeBytes,
        uploadedBy: null,
        source: "EMAIL",
      });
      const file: FileRow = await recordScanResult(tx, firmId, p.fileId, "PENDING", p.scan.status, { sha256: p.scan.sha256, sizeBytes: p.scan.sizeBytes });
      await audit(tx, system, "file", file.id, "create", null, { filename: file.filename, scanStatus: file.scanStatus, source: "EMAIL", inboundEmailId: email.id });
      if (file.scanStatus !== "CLEAN") {
        await recordUsage(tx, firm, { extractionId: null, fileId: file.id, pages: 0, billable: false, reason: "SCAN_REJECTED", costCents: null });
        d.log.warn({ firm_id: firmId, file_id: file.id, signature: p.scan.signature }, "infected email attachment quarantined");
        continue;
      }
      const r = await attachEvidence(tx, system, { timesheet: null, file, source: "EMAIL", inboundEmailId: email.id, consultantId });
      out.push(...r.jobs);
    }
    if (out.length === 0) await settleInboundEmail(tx, system, email.id, "Couldn't match the attachments automatically");
    const shouldReply = firm.timesheetAutoReply && !isAutoGenerated(msg.headers) && !msg.from.endsWith(`@${d.config.inboundDomain}`);
    return {
      jobs: out,
      autoReply: shouldReply ? autoReplyEmail({ to: msg.from, from: firm.timesheetInboxAddress, subject: msg.subject, inReplyTo: msg.messageId }) : null,
    };
  });
  for (const j of jobs) await d.jobs.send(j.name, j.data as never, { singletonKey: j.singletonKey });
  if (autoReply && d.email.enabled) {
    try {
      await d.email.send(autoReply);
    } catch (err) {
      d.log.warn({ err, firm_id: firmId }, "auto-reply failed");
    }
  }
}
